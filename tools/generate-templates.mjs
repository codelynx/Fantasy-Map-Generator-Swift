// Writes Sources/FantasyMapCore/Land/HeightmapTemplates.swift from the ORIGINAL's src/data/heightmap-templates.ts, so the
// fourteen template scripts are carried over by program and not retyped. Usage:
//   node tools/generate-templates.mjs <clone of Azgaar/Fantasy-Map-Generator> > Sources/FantasyMapCore/Land/HeightmapTemplates.swift
// The templates are step scripts in the original's (MIT-licensed) source; the port's acknowledgements cover them. A test
// compares the generated table with the template table the original's own code holds (heights-original.json).
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";

const clone = resolve(process.argv[2] ?? "");
const source = readFileSync(join(clone, "src/data/heightmap-templates.ts"), "utf8");
const commit = execFileSync("git", ["-C", clone, "rev-parse", "HEAD"]).toString().trim();

const scripts = new Map();
for (const m of source.matchAll(/^const (\w+) = `([^`]*)`;/gm)) scripts.set(m[1], m[2]);
const rows = [...source.matchAll(/^\s+(\w+): \{ id: (\d+), name: "([^"]+)", template: (\w+), probability: (\d+) \}/gm)];
if (rows.length !== 14 || scripts.size !== 14) throw new Error(`expected 14 templates, found ${rows.length} rows and ${scripts.size} scripts`);

const esc = s => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
let out = `// GENERATED by tools/generate-templates.mjs from the original's src/data/heightmap-templates.ts (Azgaar's Fantasy Map
// Generator, MIT; see ACKNOWLEDGEMENTS.md), read at commit ${commit}. Do not edit by hand.
//
// The fourteen land shapes of the original: each is a script of height steps, one per line, in the original's step
// format, with the probability weight the original gives it when it picks a template at random.

/// A named land shape: a script of height steps.
public struct HeightmapTemplate: Equatable, Sendable {
	/// The original's index for this template (0 ... 13).
	public let id: Int
	/// The original's key, for example \`highIsland\`.
	public let key: String
	/// The original's display name, for example "High Island".
	public let name: String
	/// The relative weight the original gives this template when it chooses one at random.
	public let probability: Int
	/// The steps, one per element, each as \`Tool a b c d\` in the original's format.
	public let steps: [String]
}

extension HeightmapTemplate {
	/// The original's fourteen templates, in its order.
	public static let all: [HeightmapTemplate] = [
`;
out += rows.map(m => {
	const [, key, id, name, ident, probability] = m;
	const steps = scripts.get(ident).split("\n").map(l => l.trim());
	return `\t\tHeightmapTemplate(id: ${id}, key: "${key}", name: "${esc(name)}", probability: ${probability}, steps: [\n${steps.map(l => `\t\t\t"${esc(l)}"`).join(",\n")}\n\t\t])`;
}).join(",\n");
out += `
	]

	/// The template with the given key (\`volcano\`, \`highIsland\`, ...), or nil.
	public static func named(_ key: String) -> HeightmapTemplate? { all.first { $0.key == key } }
}
`;
process.stdout.write(out);
